function pdf(
  file: string,
  pages: string,
  url: string,
  firstPage = 1,
): SourceRef {
  return {
    file,
    pages,
    href: `${url}#page=${firstPage}`,
    originalUrl: "",
    format: "pdf",
  };
}

function web(file: string, url: string): SourceRef {
  return {
    file,
    pages: "Web source",
    href: url,
    originalUrl: "",
    format: "web",
  };
}

